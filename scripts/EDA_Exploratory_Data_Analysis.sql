/*
---------------------
Magnitude Analysis
---------------------
--Comparing the measure values across different categories and dimensions;
-- [Measure] By [Dimension] 
--EG: Total sales By country
--Total Quantity by category 
*/

--Find Total number of Custimers by country
SELECT 
	COUNT(customer_key) as customers, 
	country
FROM gold.dim_customers
GROUP BY country

--Find total customers by gender
SELECT 
	COUNT(customer_key) as customers, 
	gender
FROM gold.dim_customers
GROUP BY gender
--What is the avg cost in each category ?
SELECT 
	category_name,
	AVG(cost) as cost
FROM gold.dim_products
GROUP BY category_name
--What is the total revenure generated in each category ?
SELECT 
	p.category_name as category,
	SUM(f.sales_amount) as total_sales 
FROM gold.fact_sales AS f
LEFT JOIN gold.dim_products as p
ON p.product_key = f.product_key
GROUP BY p.category_name

--Find the total revenue that is generated by each customer ?
SELECT 
	customer_key AS customer,
	SUM(sales_amount) as sales
FROM gold.fact_sales
GROUP BY customer_key
--What is the distribution of sold items across countries ? 

SELECT 
c.country,
sum(f.quantity) as total_items_sold
FROM gold.fact_sales as f
LEFT JOIN gold.dim_customers as c
on c.customer_key = f.customer_key
group by c.country


/*
---------------------
Ranking Analysis
--------------------- 
*/

--Which 5 products generate the highest revenue

SELECT TOP 5
	p.product_name,
	SUM(f.sales_amount) AS total_sales
FROM gold.fact_sales AS f
LEFT JOIN gold.dim_products AS p
ON p.product_key = f.product_key
GROUP BY product_name
ORDER BY total_sales DESC

--For complex then use ranking functions
SELECT * FROM 
(
SELECT 
	p.product_name,
	SUM(f.sales_amount) AS total_sales,
	ROW_NUMBER() OVER(ORDER BY SUM(f.sales_amount) DESC) as ranking
FROM gold.fact_sales AS f
LEFT JOIN gold.dim_products AS p
ON p.product_key = f.product_key
GROUP BY product_name
)t
WHERE ranking <= 5

--What are the 5 worst performing products 
SELECT TOP 5
	p.product_name,
	SUM(f.sales_amount) AS total_sales
FROM gold.fact_sales AS f
LEFT JOIN gold.dim_products AS p
ON p.product_key = f.product_key
GROUP BY product_name
ORDER BY total_sales ASC

